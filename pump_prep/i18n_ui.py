def packs_json() -> str:
    """Embeddable JSON for dashboard/launch scripts."""
    return json.dumps(UI, ensure_ascii=False)


def write_static_packs(out_dir: Path | None = None) -> Path:
    """Write out/i18n.json for /i18n.json and launch refresh."""
    from pump_prep.config import ROOT

    out = Path(out_dir) if out_dir else (ROOT / "out")
    out.mkdir(parents=True, exist_ok=True)
    path = out / "i18n.json"
    path.write_text(packs_json(), encoding="utf-8")
    # Keep launch.html I18N object in sync if present
    launch = out / "launch.html"
    if launch.exists():
        text = launch.read_text(encoding="utf-8")
        import re

        new, n = re.subn(
            r"const I18N = \{.*?\};",
            "const I18N = " + packs_json() + ";",
            text,
            count=1,
            flags=re.DOTALL,
        )
        if n:
            launch.write_text(new, encoding="utf-8")
    return path


def t(lang: str, key: str, **fmt: Any) -> str:
    pack = UI.get(lang) or UI[DEFAULT_LANG]
    s = pack.get(key) or UI[DEFAULT_LANG].get(key) or key
    if fmt:
        try:
            return s.format(**fmt)
        except (KeyError, ValueError):
            return s
    return s


def normalize_lang(lang: str | None) -> str:
    v = (lang or "").lower().strip()
    if v in ("ua", "ukr", "украинский", "українська"):
        return "uk"
    if v in LANGS:
        return v
    return DEFAULT_LANG
